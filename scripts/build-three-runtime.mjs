// npm install --no-save --package-lock=false three@0.169.0 esbuild@0.25.11
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const license = await readFile(new URL('../LICENSE', import.meta.resolve('three')), 'utf8');
const symbols = `
  ACESFilmicToneMapping, AdditiveBlending, BackSide, Box3, BoxGeometry, BufferAttribute,
  BufferGeometry, Color, CylinderGeometry, DataTexture, DirectionalLight, DoubleSide,
  DynamicDrawUsage, ExtrudeGeometry, Float32BufferAttribute, Group, HemisphereLight,
  LatheGeometry, Line, LineBasicMaterial, LinearFilter, Mesh, MeshBasicMaterial,
  MeshPhysicalMaterial, MeshStandardMaterial, OrthographicCamera, Plane, PlaneGeometry,
  PMREMGenerator, PointLight, Points, Quaternion, Raycaster, Scene, ShaderMaterial, Shape,
  ShapeUtils, SpotLight, SRGBColorSpace, TorusGeometry, UniformsUtils, Vector2, Vector3,
  Vector4, WebGLRenderer, WebGLRenderTarget
`;

await build({
  stdin: {
    contents: `
      import { ${symbols} } from 'three';
      import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
      globalThis.THREE = { ${symbols}, GLTFLoader };
    `,
    resolveDir: root,
  },
  outfile: `${root}assets/vendor/three.runtime.js`,
  bundle: true,
  minify: true,
  target: 'es2020',
  legalComments: 'inline',
  banner: { js: `/* Three.js r169 + GLTFLoader. Generated by scripts/build-three-runtime.mjs.\n${license.trim()}\n*/` },
});
